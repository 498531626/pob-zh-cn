"""Compile reviewed crafting clauses without rebuilding unrelated dictionaries."""
from collections import Counter
import json
from pathlib import Path
import re

HERE = Path(__file__).resolve().parent


def build():
    reviewed = json.loads((HERE / 'crafting-reviewed.json').read_text('utf8'))
    reviewed.update(json.loads((HERE / 'crafting-grafts.json').read_text('utf8')))
    types = json.loads((HERE / 'crafting-types.json').read_text('utf8'))
    reviewed.update(types['exact'])
    for kind, kind_zh in types['defenceTypes'].items():
        for defence, defence_zh in types['defences'].items():
            reviewed[kind + ': ' + defence] = kind_zh + '：' + defence_zh
    families = json.loads((HERE / 'crafting-families.json').read_text('utf8'))
    for family in families:
        for term, chinese in family['terms'].items():
            for en, zh in family['clauses'].items():
                reviewed[en.replace('@term@', term)] = zh.replace('@term@', chinese)
    rows = []
    for en, zh in sorted(reviewed.items()):
        ids = re.findall(r'\{\d+\}', en)
        if Counter(ids) != Counter(re.findall(r'\{\d+\}', zh)):
            raise ValueError('Crafting placeholder mismatch: ' + en)
        parts = re.split(r'(\{\d+\}|\s+)', en)
        pattern = '^' + ''.join('([%+%-]?[%d%.%(%)%-]+)' if re.fullmatch(r'\{\d+\}', p)
                               else '%s+' if p.isspace()
                               else re.sub(r'([\^$()%.\[\]*+?\-])', r'%\1', p)
                               for p in parts) + '$'
        row = dict(en=en, zh=zh, pattern=pattern, values=len(ids))
        rows.append('{' + ','.join(k+'='+json.dumps(v, ensure_ascii=False)
                                 for k, v in row.items()) + '},\n')
    (HERE.parents[1] / 'src/Localization/CraftingTemplates.lua').write_text(
        '-- Generated by tools/localization/build_crafting_locale.py.\nreturn {\n' + ''.join(rows) + '}\n', 'utf8')
    return ''.join(reviewed.values())


if __name__ == '__main__':
    build()
